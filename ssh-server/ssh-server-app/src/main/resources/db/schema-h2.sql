CREATE TABLE IF NOT EXISTS ssh_connection (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  connection_id VARCHAR(64) NOT NULL DEFAULT '',
  name VARCHAR(64) NOT NULL DEFAULT '',
  host VARCHAR(128) NOT NULL DEFAULT '',
  port INT NOT NULL DEFAULT 22,
  username VARCHAR(64) NOT NULL DEFAULT '',
  auth_type VARCHAR(16) NOT NULL DEFAULT 'PASSWORD',
  password VARCHAR(1024),
  private_key CLOB,
  status TINYINT NOT NULL DEFAULT 0,
  user_id VARCHAR(64) NOT NULL DEFAULT '',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted TINYINT NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_ssh_connection_id ON ssh_connection(connection_id);
CREATE INDEX IF NOT EXISTS idx_ssh_connection_user_id ON ssh_connection(user_id);

CREATE TABLE IF NOT EXISTS ssh_connection_config (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  connection_id VARCHAR(64) NOT NULL DEFAULT '',
  connect_timeout INT NOT NULL DEFAULT 5000,
  keepalive_interval INT NOT NULL DEFAULT 30000,
  startup_command VARCHAR(512),
  strict_host_key_check TINYINT NOT NULL DEFAULT 0,
  compression TINYINT NOT NULL DEFAULT 0,
  known_hosts CLOB,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_ssh_connection_config_id ON ssh_connection_config(connection_id);

CREATE TABLE IF NOT EXISTS llm_config (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  config_id VARCHAR(64) NOT NULL DEFAULT '',
  provider_name VARCHAR(64) NOT NULL DEFAULT '',
  base_url VARCHAR(255) NOT NULL DEFAULT '',
  api_key VARCHAR(1024),
  model VARCHAR(128) NOT NULL DEFAULT '',
  completions_path VARCHAR(255) NOT NULL DEFAULT '',
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_llm_config_id ON llm_config(config_id);
